import { afterEach, test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, copyFileSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const checker = resolve('scripts/check-staged-file-tokens.mjs');
const roots = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});
function git(root, ...args) {
  return execFileSync('git', ['-C', root, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
}
function put(root, path, content) {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), content);
}
function repo(allowlist = []) {
  const root = mkdtempSync(join(tmpdir(), 'xiaok-file-tokens-'));
  roots.push(root);
  git(root, 'init', '--initial-branch=main');
  git(root, 'config', 'core.autocrlf', 'false');
  git(root, 'config', 'user.name', 'Fixture');
  git(root, 'config', 'user.email', 'fixture@example.invalid');
  // Disable inherited hooks for fixtures; the hook integration test enables its copy.
  git(root, 'config', 'core.hooksPath', '.disabled-hooks');
  put(root, 'scripts/file-token-allowlist.json', JSON.stringify(allowlist));
  git(root, 'add', '.');
  return root;
}
function check(root) {
  return spawnSync(process.execPath, [checker], { cwd: root, encoding: 'utf8' });
}
function stage(root, path, content) {
  put(root, path, content);
  git(root, 'add', '--', path);
}

test('accepts 20,000 bytes and rejects 20,001 bytes with splitting instructions, even before first commit', () => {
  const root = repo();
  stage(root, 'limit.ts', 'a'.repeat(20_000));
  assert.equal(check(root).status, 0);
  stage(root, 'limit.ts', 'a'.repeat(20_001));
  const result = check(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /limit\.ts.*20001.*5000\.25/);
  assert.match(result.stderr, /按职责拆分/);
  assert.match(result.stderr, /git add/);
});

test('uses staged bytes in both directions and ignores unstaged and untracked large files', () => {
  const root = repo();
  stage(root, 'partial.ts', 'small');
  put(root, 'partial.ts', 'a'.repeat(30_000));
  put(root, 'untracked.ts', 'a'.repeat(30_000));
  assert.equal(check(root).status, 0);
  git(root, 'add', '--', 'partial.ts');
  put(root, 'partial.ts', 'small');
  assert.equal(check(root).status, 1);
});

test('counts UTF-8 bytes and safely reports spaces, tabs, newlines and pathspec-like names', () => {
  const root = repo();
  const paths = ['空 格.ts', ...(process.platform === 'win32' ? [] : ['tab\tname.ts', 'line\nname.ts', ':(glob)*.ts'])];
  for (const path of paths) stage(root, path, '中'.repeat(6667));
  const result = check(root);
  assert.equal(result.status, 1);
  for (const path of paths) assert.ok(result.stderr.includes(JSON.stringify(path)));
  assert.match(result.stderr, /20001/);
});

test('skips lockfiles, generated outputs, generated headers, binary files and symlinks', () => {
  const root = repo();
  const large = 'a'.repeat(30_000);
  for (const path of ['package-lock.json', 'desktop/yarn.lock', 'pnpm-lock.yaml', 'Cargo.lock', 'Podfile.lock', 'deno.lock', 'Package.resolved', 'packages.lock.json', 'gradle.lockfile',
    'dist/index.js', 'desktop/.generated/service.ts', 'api.generated.ts', 'service.pb.go',
    '.lint-baseline.json', '.architecture-baseline.json']) stage(root, path, large);
  stage(root, 'generated-header.ts', '// Code generated by generator. DO NOT EDIT.\n' + large);
  stage(root, 'generated-schema.ts', '/* @generated */\n' + large);
  stage(root, 'opaque.dat', Buffer.alloc(30_000));
  if (process.platform !== 'win32') {
    symlinkSync('untracked.ts', join(root, 'link.ts'));
    git(root, 'add', '--', 'link.ts');
  }
  assert.equal(check(root).status, 0);
});

test('binary detection uses the staged blob even when HEAD is binary or worktree attributes say binary', () => {
  const root = repo();
  stage(root, 'changed.ts', Buffer.alloc(30_000));
  git(root, 'commit', '-m', 'binary baseline');
  stage(root, 'changed.ts', 'a'.repeat(30_000));
  assert.equal(check(root).status, 1);
  put(root, '.gitattributes', 'changed.ts binary\n');
  assert.equal(check(root).status, 1);
});

test('a generated declaration in handwritten body text does not exempt the file', () => {
  const root = repo();
  stage(root, 'manual.ts', 'export const x = 1;\n// @generated documentation example\n' + 'a'.repeat(30_000));
  assert.equal(check(root).status, 1);
});

test('respects staged linguist-generated attributes without using unstaged changes', () => {
  const root = repo();
  stage(root, '.gitattributes', 'schema.ts linguist-generated=true\n');
  stage(root, 'schema.ts', 'a'.repeat(30_000));
  assert.equal(check(root).status, 0);
  stage(root, '.gitattributes', 'schema.ts -linguist-generated\n');
  put(root, '.gitattributes', 'schema.ts linguist-generated=true\n');
  assert.equal(check(root).status, 1);
});

test('only exact allowlisted paths are exempt and unstaged whitelist edits have no effect', () => {
  const root = repo(['legacy.ts']);
  stage(root, 'legacy.ts', 'a'.repeat(30_000));
  assert.equal(check(root).status, 0);
  stage(root, 'new.ts', 'a'.repeat(30_000));
  put(root, 'scripts/file-token-allowlist.json', JSON.stringify(['legacy.ts', 'new.ts']));
  assert.equal(check(root).status, 1);
});

test('checks rename destinations and ignores deleted and unchanged oversized files', () => {
  const root = repo();
  stage(root, 'old.ts', 'a'.repeat(30_000));
  git(root, 'commit', '-m', 'existing large file');
  stage(root, 'small.ts', 'small');
  assert.equal(check(root).status, 0);
  git(root, 'mv', 'old.ts', 'renamed.ts');
  assert.equal(check(root).status, 1);
  git(root, 'rm', '-f', 'renamed.ts');
  assert.equal(check(root).status, 0);
});

test('generated markers are read from the index and do not exempt handwritten files by broad directory', () => {
  const root = repo();
  stage(root, 'generated/manual.ts', 'a'.repeat(30_000));
  put(root, 'generated/manual.ts', '// @generated\n' + 'a'.repeat(30_000));
  assert.equal(check(root).status, 1);
});

test('malformed staged allowlist fails with a useful diagnostic', () => {
  const root = repo();
  stage(root, 'large.ts', 'a'.repeat(30_000));
  stage(root, 'scripts/file-token-allowlist.json', '{broken');
  const result = check(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /file-token-allowlist\.json/);
});

test('the real pre-commit hook prevents a commit and keeps the existing docs check', { skip: process.platform === 'win32' }, () => {
  const root = repo();
  mkdirSync(join(root, '.githooks'));
  copyFileSync(resolve('.githooks/pre-commit'), join(root, '.githooks/pre-commit'));
  copyFileSync(checker, join(root, 'scripts/check-staged-file-tokens.mjs'));
  copyFileSync(resolve('scripts/check-external-docs.mjs'), join(root, 'scripts/check-external-docs.mjs'));
  symlinkSync('../mydocs', join(root, 'docs'));
  git(root, 'config', 'core.hooksPath', '.githooks');
  stage(root, 'blocked.ts', 'a'.repeat(20_001));
  const result = spawnSync('git', ['-C', root, 'commit', '-m', 'must fail'], { encoding: 'utf8' });
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /blocked\.ts/);
  stage(root, 'blocked.ts', 'small');
  assert.doesNotThrow(() => git(root, 'commit', '-m', 'small file passes both checks'));
});
