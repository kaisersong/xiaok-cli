import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.argv[2];
if (!['normal', 'release', 'rollback'].includes(mode)) throw new Error('build type must be normal, release or rollback');
function git(...args) {
  try { return execFileSync('git', args, {cwd: root, encoding:'utf8', stdio:['ignore','pipe','ignore'], timeout:5000}).trim(); }
  catch { return null; }
}
const epoch = process.env.SOURCE_DATE_EPOCH;
if (epoch && (!/^\d+$/.test(epoch) || !Number.isSafeInteger(Number(epoch)) || !Number.isFinite(new Date(Number(epoch) * 1000).getTime()))) {
  throw new Error('SOURCE_DATE_EPOCH must be a valid non-negative integer timestamp');
}
const builtAt = epoch ? new Date(Number(epoch) * 1000).toISOString() : mode === 'normal' ? new Date().toISOString() : null;
const dirty = git('status', '--porcelain=v1', '--untracked-files=normal', '--', '.',
  ':(exclude)dist/**', ':(exclude).test-dist/**', ':(exclude)src/build-info.ts', ':(exclude)src/build-flavor.ts');
const info = {
  version: JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version,
  commit: git('rev-parse', 'HEAD'), branch: git('branch', '--show-current') || null,
  dirty: dirty === null ? null : Boolean(dirty), sourceDate: git('show', '-s', '--format=%cI', 'HEAD'),
  builtAt, buildType: mode, node: process.version, platform: process.platform, arch: process.arch,
};
const localTime = builtAt ? new Date(builtAt) : null;
const pad = number => String(number).padStart(2, '0');
const buildTime = mode === 'normal' && localTime
  ? `${localTime.getFullYear()}-${pad(localTime.getMonth() + 1)}-${pad(localTime.getDate())} ${pad(localTime.getHours())}:${pad(localTime.getMinutes())}`
  : null;
writeFileSync(join(root, 'src', 'build-info.ts'),
  `// Generated by scripts/set-build-info.mjs; build provenance excludes this generated file.\n`
  + `import type { BuildMetadata } from './build-metadata.js';\n`
  + `export const BUILD_TIME: string | null = ${JSON.stringify(buildTime)};\n`
  + `export const BUILD_INFO: BuildMetadata = ${JSON.stringify(info, null, 2)};\n`);
